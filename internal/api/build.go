// buildRequest is the body of POST /api/network/build: the box to fetch and the
// road classes to keep.
type buildRequest struct {
	overpass.Area
	// Classes are OSM highway values. Empty means the arterials.
	Classes []string `json:"classes"`
	// Install loads the result as the active network. When false the caller
	// only wants the file, which is what the download link uses.
	Install bool `json:"install"`
}

// buildResponse describes what a build produced.
type buildResponse struct {
	// Network describes the graph now loaded, when Install was set.
	Network networkResponse `json:"network"`
	// Bytes is the size of the generated .net.xml.
	Bytes int `json:"bytes"`
	// OSMWays is how many ways the area returned before conversion, which is the
	// number that tells an operator their box was empty or their classes too
	// narrow.
	OSMWays int `json:"osm_ways"`
	// DurationMS is how long the whole build took, including the upstream call.
	DurationMS int64 `json:"duration_ms"`
}

// buildTimeout bounds one build. Overpass answers a city box in seconds, but a
// public endpoint can be at capacity; this is the point at which waiting longer
// is worse than a clear failure.
const buildTimeout = 3 * time.Minute

// handleBuildNetwork answers POST /api/network/build.
//
// It fetches the roads for the requested area, converts them to a SUMO network,
// and — unless the caller only wanted the file — installs the result as the
// network the server routes over. The generated bytes are kept so the operator
// can download the file they just built.
func (s *Server) handleBuildNetwork(w http.ResponseWriter, r *http.Request) {
	if s.runInUse() {
		writeError(w, r, domain.Conflict(codeNetworkBusy,
			"a comparison run is going or starting: stop it before building a different network"))
		return
	}

	// One build at a time. Two would race for the single download slot, and
	// could install two graphs in an order nobody chose.
	if !buildMu.TryLock() {
		writeError(w, r, domain.Conflict(codeBuildInProgress,
			"a network build is already running; wait for it to finish"))
		return
	}
	defer buildMu.Unlock()

	var req buildRequest
	decoder := json.NewDecoder(http.MaxBytesReader(w, r.Body, 4<<10))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&req); err != nil {
		writeError(w, r, domain.Invalid(codeBuildBodyInvalid, "could not read the build request: %v", err))
		return
	}

	if err := req.Area.Validate(); err != nil {
		if errors.Is(err, overpass.ErrAreaTooLarge) {
			writeError(w, r, domain.Invalid(codeBuildAreaTooLarge, "%s", err.Error()))
			return
		}
		writeError(w, r, domain.Invalid(codeBuildAreaInvalid, "%s", err.Error()))
		return
	}

	classes, classErr := buildClasses(req.Classes)
	if classErr != nil {
		writeError(w, r, classErr)
		return
	}

	// The build outlives the request deadline: Overpass is allowed to take
	// minutes, and a client hanging up mid-build should not leave a half-swapped
	// graph behind. The deadline is the build's own.
	ctx, cancel := context.WithTimeout(context.WithoutCancel(r.Context()), buildTimeout)
	defer cancel()

	started := time.Now()
	builder := &overpass.Builder{Endpoint: s.overpassEndpoint}
	osm, err := builder.Fetch(ctx, req.Area, classes)
	if err != nil {
		writeError(w, r, buildError(err))
		return
	}

	netXML, err := overpass.NetXML(osm)
	if err != nil {
		writeError(w, r, buildError(err))
		return
	}

	g, err := graph.ImportSUMONetwork(bytes.NewReader(netXML),
		graph.ImportOptions{MinLengthM: 1, KeepLargestComponent: true})
	if err != nil {
		writeError(w, r, networkImportError(err))
		return
	}

	name := r.Header.Get("X-Network-Name")
	if name == "" {
		name = "area network"
	}

	if req.Install {
		if err := s.installGraph(g, name, "area"); err != nil {
			writeError(w, r, err)
			return
		}
	}

	s.networkMu.Lock()
	s.builtNetwork = netXML
	s.builtNetworkName = name
	s.networkMu.Unlock()

	loggerFromContext(r.Context()).Info("built a road network from an area",
		"nodes", len(g.Nodes), "edges", len(g.Edges),
		"bytes", len(netXML), "installed", req.Install)

	writeJSON(w, http.StatusOK, buildResponse{
		Network:    networkOf(g, name, sourceFor(req.Install)),
		Bytes:      len(netXML),
		OSMWays:    countOSMWays(osm),
		DurationMS: time.Since(started).Milliseconds(),
	})
}

// sourceFor labels a network by whether it was installed or only generated.
func sourceFor(installed bool) string {
	if installed {
		return "area"
	}
	return "generated"
}

// handleDownloadNetwork answers GET /api/network/build/download with the last
// generated .net.xml, so an operator can keep the file they built.
func (s *Server) handleDownloadNetwork(w http.ResponseWriter, r *http.Request) {
	s.networkMu.RLock()
	body, name := s.builtNetwork, s.builtNetworkName
	s.networkMu.RUnlock()

	if len(body) == 0 {
		writeError(w, r, domain.Invalid(codeBuildNotBuilt,
			"no network has been built yet: select an area first"))
		return
	}

	w.Header().Set("Content-Type", "application/xml; charset=utf-8")
	w.Header().Set("Content-Disposition", `attachment; filename="`+downloadName(name)+`.net.xml"`)
	w.WriteHeader(http.StatusOK)
	_, _ = w.Write(body)
}

// downloadName reduces a network name to something safe in a header.
func downloadName(name string) string {
	safe := make([]rune, 0, len(name))
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_':
			safe = append(safe, r)
		case r == ' ':
			safe = append(safe, '-')
		}
	}
	if len(safe) == 0 {
		return "network"
	}
	return string(safe)
}

// buildClasses validates the requested road classes against the ones the builder
// knows, so a typo is refused instead of silently producing an empty query.
func buildClasses(requested []string) ([]string, error) {
	if len(requested) == 0 {
		return nil, nil
	}
	known := make(map[string]bool, len(overpass.RoadClasses))
	for _, c := range overpass.RoadClasses {
		known[c] = true
	}
	out := make([]string, 0, len(requested))
	for _, c := range requested {
		if !known[c] {
			return nil, domain.Invalid(codeBuildClassUnknown,
				"unknown road class %q; choose from %v", c, overpass.RoadClasses)
		}
		out = append(out, c)
	}
	return out, nil
}

// buildError maps a builder failure to the transport's error shape.
func buildError(err error) error {
	switch {
	case errors.Is(err, overpass.ErrAreaTooLarge):
		return domain.Invalid(codeBuildAreaTooLarge, "%s", err.Error())
	case errors.Is(err, overpass.ErrNoRoads):
		return domain.Invalid(codeBuildNoRoads,
			"the selected area contains no roads of those classes; try a larger box or more classes")
	case errors.Is(err, overpass.ErrUpstream):
		return domain.Unavailable(codeBuildUpstream,
			"the road data service could not be reached: %s", err.Error())
	default:
		return domain.Invalid(codeBuildFailed, "could not build the network: %s", err.Error())
	}
}

// countOSMWays counts the <way> elements in an OSM document, which is the number
// an operator needs to tell "no roads here" from "the roads did not convert".
func countOSMWays(doc []byte) int {
	return bytes.Count(doc, []byte("<way "))
}

// build error codes. They travel in API error bodies, so they are part of the
// public contract and must stay stable.
const (
	codeBuildBodyInvalid  = "build_body_invalid"
	codeBuildAreaInvalid  = "build_area_invalid"
	codeBuildAreaTooLarge = "build_area_too_large"
	codeBuildClassUnknown = "build_class_unknown"
	codeBuildNoRoads      = "build_no_roads"
	codeBuildUpstream     = "build_upstream_unavailable"
	codeBuildFailed       = "build_failed"
	codeBuildNotBuilt     = "build_not_built"
	codeBuildInProgress   = "build_in_progress"
)

// buildMu serializes builds. Two concurrent builds would race for the single
// download slot and could install two graphs in an order nobody chose.
var buildMu sync.Mutex
